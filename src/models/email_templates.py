"""
Email Templates Models

Section-based email templates with support for both static content
and AI-generated personalized sections.
"""

from sqlalchemy import Column, Integer, String, Boolean, DateTime, Text, JSON, ForeignKey, Index, Enum as SQLEnum
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func
from typing import Dict, Any, Optional, List
from enum import Enum

from src.models.database import BaseModel


class TemplateSectionType(str, Enum):
    """Types of email template sections."""
    STATIC = "static"  # User-defined static text with variable substitution
    AI_GENERATED = "ai_generated"  # AI-generated personalized content


class TemplateCategory(str, Enum):
    """Email template categories."""
    APPLICANT_FOLLOWUP = "applicant_followup"
    MARKET_OUTREACH = "market_outreach"
    INTERVIEW_INVITE = "interview_invite"
    REJECTION = "rejection"
    CUSTOM = "custom"


class EmailTemplate(BaseModel):
    """
    Email template with section-based content.
    
    Templates can contain multiple sections, each either:
    - Static: Fixed text with variable substitution ({{candidate_name}})
    - AI Generated: Personalized content generated per candidate
    """
    __tablename__ = "email_templates"
    
    # Identity
    customer_id = Column(String(100), ForeignKey("customers.customer_id"), nullable=False, index=True)
    
    # Template metadata
    name = Column(String(255), nullable=False)
    description = Column(Text, nullable=True)
    category = Column(String(50), nullable=False, default=TemplateCategory.CUSTOM.value)
    
    # Subject line (can contain variables)
    subject = Column(Text, nullable=False)
    subject_is_ai_generated = Column(Boolean, default=False, nullable=False)
    subject_ai_prompt = Column(Text, nullable=True)  # Prompt if AI-generated
    
    # Usage tracking
    use_count = Column(Integer, default=0, nullable=False)
    last_used_at = Column(DateTime(timezone=True), nullable=True)
    
    # Status
    is_active = Column(Boolean, default=True, nullable=False)
    is_default = Column(Boolean, default=False, nullable=False)  # Default template for category
    
    # Relationships
    sections = relationship(
        "EmailTemplateSection", 
        back_populates="template",
        order_by="EmailTemplateSection.section_order",
        cascade="all, delete-orphan"
    )
    
    __table_args__ = (
        Index('ix_email_template_customer', 'customer_id'),
        Index('ix_email_template_category', 'customer_id', 'category'),
        Index('ix_email_template_active', 'customer_id', 'is_active'),
        {'extend_existing': True}
    )
    
    def get_all_variables(self) -> List[str]:
        """Extract all variables used in this template."""
        import re
        variables = set()
        
        # Check subject
        matches = re.findall(r'\{\{(\w+)\}\}', self.subject or '')
        variables.update(matches)
        
        # Check all sections
        for section in self.sections:
            if section.content:
                matches = re.findall(r'\{\{(\w+)\}\}', section.content)
                variables.update(matches)
            if section.ai_prompt:
                matches = re.findall(r'\{\{(\w+)\}\}', section.ai_prompt)
                variables.update(matches)
        
        return sorted(list(variables))


class EmailTemplateSection(BaseModel):
    """
    A section within an email template.
    
    Sections are ordered and can be either:
    - Static: Content is used as-is (with variable substitution)
    - AI Generated: Content is generated by AI using the prompt and context
    """
    __tablename__ = "email_template_sections"
    
    # Parent template
    template_id = Column(Integer, ForeignKey("email_templates.id", ondelete="CASCADE"), nullable=False, index=True)
    
    # Ordering - Python attribute 'section_order' maps to DB column 'order'
    section_order = Column("order", Integer, nullable=False, default=0)
    
    # Section type
    section_type = Column(String(50), nullable=False, default=TemplateSectionType.STATIC.value)
    
    # For static sections: the actual content with variables
    content = Column(Text, nullable=True)
    
    # For AI-generated sections
    ai_prompt = Column(Text, nullable=True)  # e.g., "Write a personalized opening about their skills"
    ai_context_fields = Column(JSON, nullable=True)  # ['candidate_skills', 'job_title', 'company_name']
    ai_tone = Column(String(50), nullable=True, default="professional")  # professional, casual, enthusiastic
    ai_max_length = Column(Integer, nullable=True, default=200)  # Max characters for generated content
    
    # Section metadata
    section_name = Column(String(100), nullable=True)  # e.g., "Opening", "Skills Match", "Call to Action"
    
    # Relationships
    template = relationship("EmailTemplate", back_populates="sections")
    
    __table_args__ = (
        Index('ix_template_section_order', 'template_id', 'order'),
        {'extend_existing': True}
    )


