class GeneratedEmail(BaseModel):
    """
    Stores generated email content for a specific candidate.
    
    Caches the AI-generated content so we don't regenerate on every view.
    Also allows manual editing before sending.
    """
    __tablename__ = "generated_emails"
    
    # Identity
    customer_id = Column(String(100), ForeignKey("customers.customer_id"), nullable=False, index=True)
    template_id = Column(Integer, ForeignKey("email_templates.id"), nullable=True)
    
    # Candidate reference
    candidate_id = Column(String(255), nullable=False, index=True)  # PDL ID or applicant ID
    talent_analysis_id = Column(String(100), ForeignKey("talent_analyses.analysis_id"), nullable=True)
    
    # Generated content
    subject = Column(Text, nullable=False)
    body = Column(Text, nullable=False)
    
    # Editing tracking
    is_edited = Column(Boolean, default=False, nullable=False)
    original_subject = Column(Text, nullable=True)  # Before any edits
    original_body = Column(Text, nullable=True)  # Before any edits
    
    # Generation metadata
    generation_context = Column(JSON, nullable=True)  # Context used for generation
    generation_model = Column(String(100), nullable=True)  # e.g., "gpt-4"
    
    # Status
    status = Column(String(50), default="draft", nullable=False)  # draft, sent, scheduled
    sent_at = Column(DateTime(timezone=True), nullable=True)
    scheduled_for = Column(DateTime(timezone=True), nullable=True)
    
    __table_args__ = (
        Index('ix_generated_email_candidate', 'customer_id', 'candidate_id'),
        Index('ix_generated_email_analysis', 'talent_analysis_id'),
        {'extend_existing': True}
    )


class PDLQueryCache(BaseModel):
    """
    Caches PDL query results to avoid redundant API calls.
    
    Stores the query hash and resulting person IDs.
    Results are valid for a configurable TTL (default 30 days).
    """
    __tablename__ = "pdl_query_cache"
    
    # Identity
    customer_id = Column(String(100), ForeignKey("customers.customer_id"), nullable=False, index=True)
    
    # Query identification
    query_hash = Column(String(64), nullable=False, index=True)  # SHA256 of normalized query
    query_params = Column(JSON, nullable=False)  # Original query parameters
    query_type = Column(String(50), nullable=False)  # "linkedin_enrichment", "search", "lookalike"
    
    # Results
    result_count = Column(Integer, nullable=False, default=0)
    result_pdl_ids = Column(JSON, nullable=True)  # List of PDL person IDs returned
    
    # Cache metadata
    cache_hit_count = Column(Integer, default=0, nullable=False)  # How many times this cache was used
    last_hit_at = Column(DateTime(timezone=True), nullable=True)
    
    # TTL tracking
    expires_at = Column(DateTime(timezone=True), nullable=False)  # When this cache entry expires
    
    __table_args__ = (
        Index('ix_pdl_cache_query', 'customer_id', 'query_hash'),
        Index('ix_pdl_cache_expires', 'expires_at'),
        {'extend_existing': True}
    )
    
    def is_valid(self) -> bool:
        """Check if cache entry is still valid."""
        from datetime import datetime, timezone
        return datetime.now(timezone.utc) < self.expires_at


