    @staticmethod
    def _parse_ideal_candidate(ideal_candidate_description: str) -> Dict[str, Any]:
        """
        Parse the ideal candidate description into structured components.
        
        The frontend sends this as JSON with structured fields:
        - mustHaves: required skills/experience
        - niceToHaves: preferred skills/experience
        - dealbreakers: disqualifying criteria
        - personalityTraits: cultural/soft skill requirements
        - hiringManagerNotes: free-form hiring manager context
        
        Falls back to treating the whole string as free-form notes.
        """
        import json as _json
        
        if not ideal_candidate_description or not ideal_candidate_description.strip():
            return {}
        
        try:
            parsed = _json.loads(ideal_candidate_description)
            if isinstance(parsed, dict):
                return parsed
        except (_json.JSONDecodeError, TypeError):
            pass
        
        return {"hiringManagerNotes": ideal_candidate_description.strip()}

    def _build_baseline_from_blueprint(
        self,
        role: str,
        ideal_candidate_description: str = ""
    ) -> BaselineProfile:
        """
        Stage 1: Build baseline profile from the Career Blueprint + ideal candidate input.
        
        Two sources are merged:
        1. Career Blueprint — patterns from enriched LinkedIn profiles (skills, companies,
           experience, career paths)
        2. Ideal Candidate Description — the user's stated must-haves, nice-to-haves,
           dealbreakers, and hiring manager notes
        
        If no blueprint is loaded, the baseline is built solely from the ideal candidate
        input. The diagnostic agent can still function with this.
        """
        # Parse the ideal candidate input
        ideal = self._parse_ideal_candidate(ideal_candidate_description)
        
        has_blueprint = self.blueprint is not None
        has_ideal = bool(ideal)
        
        if not has_blueprint and not has_ideal:
            logger.info("baseline_no_inputs", role=role)
            return BaselineProfile(
                role_type=role,
                prototype_employee_ids=[],
                attribute_weights={},
                common_career_paths=[],
                skill_distributions={},
                company_clusters=[],
                average_years_experience=5.0,
                success_patterns=[],
                data_quality_score=0.0
            )
        
        # ---- Blueprint data (if available) ----
        bp = self.blueprint
        skill_profile = (bp.skill_profile or {}) if bp else {}
        company_progression = (bp.company_progression or {}) if bp else {}
        experience_profile = (bp.experience_profile or {}) if bp else {}
        role_progression = (bp.role_progression or {}) if bp else {}
        
        # Skill distributions from Blueprint
        skill_distributions: Dict[str, float] = {}
        for skill in skill_profile.get("core_skills", []):
            skill_distributions[skill] = 1.0
        skill_freqs = skill_profile.get("skill_frequencies", {})
        for skill, freq in skill_freqs.items():
            if skill not in skill_distributions:
                skill_distributions[skill] = freq if isinstance(freq, (int, float)) else 0.5
        
        # Company clusters from Blueprint
        company_clusters = company_progression.get("common_companies", [])
        
        # Average experience from Blueprint
        avg_years = experience_profile.get("avg_years", 5.0)
        
        # Career paths from role progression
        common_titles = role_progression.get("common_titles", [])
        career_paths = []
        if common_titles:
            from src.models.talent_analysis import CareerPathPattern
            career_paths.append(CareerPathPattern(
                path_description=" → ".join(common_titles[:5]),
                frequency=(bp.source_profile_count or 1) if bp else 1,
                example_employees=(bp.source_pdl_person_ids or []) if bp else []
            ))
        
        # ---- Ideal candidate data (user input) ----
        # Must-haves get highest weight; nice-to-haves are supplementary
        must_haves = ideal.get("mustHaves", "")
        nice_to_haves = ideal.get("niceToHaves", "")
        dealbreakers = ideal.get("dealbreakers", "")
        personality_traits = ideal.get("personalityTraits", "")
        hiring_notes = ideal.get("hiringManagerNotes", "")
        
        # Extract skill-like tokens from must-haves and nice-to-haves
        # These are user-stated requirements, so they get high weight
        for text, weight in [(must_haves, 1.0), (nice_to_haves, 0.6)]:
            if text:
                tokens = [t.strip().lower() for t in text.replace("\n", ",").split(",") if t.strip()]
                for token in tokens:
                    if token and len(token) < 80:
                        if token not in skill_distributions:
                            skill_distributions[token] = weight
                        else:
                            skill_distributions[token] = max(skill_distributions[token], weight)
        
        # ---- Build success patterns from both sources ----
        success_patterns = []
        if must_haves:
            success_patterns.append(f"Must-haves: {must_haves[:200]}")
        if nice_to_haves:
            success_patterns.append(f"Nice-to-haves: {nice_to_haves[:200]}")
        if dealbreakers:
            success_patterns.append(f"Dealbreakers: {dealbreakers[:200]}")
        if personality_traits:
            success_patterns.append(f"Traits: {personality_traits[:200]}")
        if hiring_notes:
            success_patterns.append(f"Hiring notes: {hiring_notes[:200]}")
        if skill_profile.get("core_skills"):
            success_patterns.append(f"Blueprint core skills: {', '.join(skill_profile['core_skills'][:5])}")
        if company_clusters:
            success_patterns.append(f"Blueprint companies: {', '.join(company_clusters[:5])}")
        if common_titles:
            success_patterns.append(f"Blueprint titles: {', '.join(common_titles[:5])}")
        
        # Scoring weights from Blueprint (or defaults)
        attribute_weights = {}
        if bp and bp.scoring_weights:
            attribute_weights = bp.scoring_weights
        if not attribute_weights:
            attribute_weights = {
                "technical_skills": 0.30,
                "experience": 0.25,
                "trajectory": 0.20,
                "company_background": 0.15,
                "education": 0.10
            }
        
        # Data quality: blueprint profiles + ideal candidate completeness
        profile_count = (bp.source_profile_count or 0) if bp else 0
        ideal_completeness = sum(1 for v in [must_haves, nice_to_haves, personality_traits, hiring_notes] if v) / 4.0
        data_quality = min(1.0, (profile_count / 5.0) * 0.7 + ideal_completeness * 0.3)
        
        baseline = BaselineProfile(
            role_type=role or (bp.role_category if bp else "") or "",
            prototype_employee_ids=(bp.source_pdl_person_ids or []) if bp else [],
            attribute_weights=attribute_weights,
            common_career_paths=career_paths,
            skill_distributions=skill_distributions,
            company_clusters=company_clusters,
            average_years_experience=avg_years,
            success_patterns=success_patterns,
            data_quality_score=data_quality
        )
        
        logger.info(
            "baseline_built",
            has_blueprint=has_blueprint,
            blueprint_id=bp.id if bp else None,
            blueprint_name=bp.name if bp else None,
            source_profile_count=profile_count,
            ideal_fields_provided=sum(1 for v in ideal.values() if v),
            skill_count=len(skill_distributions),
            company_count=len(company_clusters),
            success_pattern_count=len(success_patterns),
            avg_years=avg_years,
            data_quality=data_quality
        )
        
        return baseline
    
    async def _run_diagnostic(
        self,
        job_description: str,
        ideal_candidate: str,
        baseline: BaselineProfile,
        role: str
    ) -> DiagnosticReport:
        """Stage 2: Run diagnostic agent."""
        diagnostic_agent = DiagnosticAgentService(
            customer_id=self.customer_id,
            user_id=self.user_id,
            llm_provider="openai",
            llm_model="gpt-4o-mini"
        )
        
        diagnostic_input = DiagnosticInput(
            job_description=job_description,
            ideal_candidate_description=ideal_candidate,
            baseline_profile=baseline,
            role=role
        )
        
        return await asyncio.to_thread(
            diagnostic_agent.analyze,
            diagnostic_input
        )
    
    async def _load_scoring_config(
        self,
        blueprint_id: Optional[int],
        company_dna_id: Optional[int]
    ) -> None:
        """
        Load Career Blueprint and Company DNA from database for dynamic scoring.
        
        Args:
            blueprint_id: Optional blueprint ID to load
            company_dna_id: Optional company DNA ID to load
        """
        from src.models.database import SessionLocal, init_database
        from src.models.talent_config import CareerBlueprint, CompanyDNAProfile
        
        # Ensure database is initialized
        if SessionLocal is None:
            init_database()
        
        db = SessionLocal()
        try:
            # Load blueprint if provided
            if blueprint_id:
                self.blueprint = db.query(CareerBlueprint).filter(
                    CareerBlueprint.id == blueprint_id,
                    CareerBlueprint.customer_id == self.customer_id,
                    CareerBlueprint.is_active == True
                ).first()
                
                if self.blueprint:
                    logger.info(
                        "loaded_career_blueprint",
                        blueprint_id=blueprint_id,
                        blueprint_name=self.blueprint.name
                    )
                else:
                    logger.warning(
                        "blueprint_not_found",
                        blueprint_id=blueprint_id,
                        customer_id=self.customer_id
                    )
            
            # Load company DNA if provided
            if company_dna_id:
                self.company_dna = db.query(CompanyDNAProfile).filter(
                    CompanyDNAProfile.id == company_dna_id,
                    CompanyDNAProfile.customer_id == self.customer_id,
                    CompanyDNAProfile.is_active == True
                ).first()
                
                if self.company_dna:
                    logger.info(
                        "loaded_company_dna",
                        dna_id=company_dna_id,
                        company_name=self.company_dna.company_name,
                        role_category=self.company_dna.role_category
                    )
                else:
                    logger.warning(
                        "company_dna_not_found",
                        dna_id=company_dna_id,
                        customer_id=self.customer_id
                    )
            
            # Always use DynamicScoringEngine - it handles missing blueprint/DNA gracefully
            # This ensures consistent scoring across all candidates
            self.scoring_engine = DynamicScoringEngine(
                blueprint=self.blueprint,
                company_dna=self.company_dna
            )
            
            # Use enhanced PDL query builder if we have blueprint or DNA
            if self.blueprint or self.company_dna:
                self.enhanced_pdl_builder = EnhancedPDLQueryBuilder(
                    blueprint=self.blueprint,
                    company_dna=self.company_dna
                )
            else:
                self.enhanced_pdl_builder = None
            
            logger.info(
                "using_dynamic_scoring_engine",
                has_blueprint=self.blueprint is not None,
                has_dna=self.company_dna is not None,
                blueprint_name=self.blueprint.name if self.blueprint else None,
                dna_company=self.company_dna.company_name if self.company_dna else None,
                using_enhanced_pdl_builder=self.enhanced_pdl_builder is not None
            )
                
        finally:
            db.close()
    
    async def _parse_resumes(
        self,
        resume_files: List[Any],
        customer_id: Optional[str] = None,
        analysis_id: Optional[str] = None
    ) -> List[ParsedResume]:
        """Stage 3: Parse applicant resumes with text extraction + LLM.
        
        Uses concurrent parsing (up to 10 simultaneous API calls) for speed.
        A batch of 100 resumes at ~12s each takes ~2 min instead of ~20 min.
        
        Accepts either:
        - Legacy format: List of (file_bytes, filename) tuples
        - Rich format: List of ApplicantResumeData or dicts with metadata
        
        Uses caching to skip parsing for candidates we've already processed.
        Emits progress events as resumes are parsed.
        """
        parsed = []
        cache_hits = 0
        cache_misses = 0
        failed_count = 0
        completed_count = 0
        total_resumes = len(resume_files)
        
        MAX_CONCURRENT_PARSES = 10
        semaphore = asyncio.Semaphore(MAX_CONCURRENT_PARSES)
        
        # Initialize candidate service for cache lookup
        candidate_service = None
        db = None
        if customer_id:
            try:
                from src.models import database
                from src.services.candidate_service import CandidateService
                if database.SessionLocal is None:
                    database.init_database()
                db = database.SessionLocal()
                candidate_service = CandidateService(db, customer_id)
            except Exception as e:
                logger.warning(f"Failed to initialize candidate service for cache: {e}")
        
        # Phase 1: Pre-process all resumes — extract metadata and check cache
        to_parse = []
        
        try:
            for idx, resume_data in enumerate(resume_files):
                try:
                    # Handle legacy tuple format: (file_bytes, filename)
                    if isinstance(resume_data, tuple) and len(resume_data) == 2:
                        file_bytes, filename = resume_data
                        metadata = {}
                    # Handle dict format from Greenhouse connector
                    elif isinstance(resume_data, dict):
                        file_bytes = resume_data.get("file_bytes")
                        filename = resume_data.get("filename", "resume.pdf")
                        raw_greenhouse_id = resume_data.get("greenhouse_id")
                        metadata = {
                            "greenhouse_id": raw_greenhouse_id or resume_data.get("candidate_id") or resume_data.get("metadata", {}).get("greenhouse_candidate_id"),
                            "candidate_name": resume_data.get("candidate_name"),
                            "candidate_email": resume_data.get("email") or resume_data.get("candidate_email"),
                            "linkedin_url": resume_data.get("linkedin_url"),
                            "phone": resume_data.get("phone"),
                            "location": resume_data.get("location"),
                        }
                        logger.info(
                            "resume_metadata_extracted",
                            raw_greenhouse_id=raw_greenhouse_id,
                            resolved_greenhouse_id=metadata.get("greenhouse_id"),
                            candidate_name=metadata.get("candidate_name"),
                            candidate_email=metadata.get("candidate_email"),
                            resume_data_keys=list(resume_data.keys())
                        )
                    # Handle ApplicantResumeData model
                    elif hasattr(resume_data, 'file_bytes'):
                        file_bytes = resume_data.file_bytes
                        filename = resume_data.filename
                        metadata = {
                            "greenhouse_id": getattr(resume_data, 'greenhouse_id', None),
                            "candidate_name": getattr(resume_data, 'candidate_name', None),
                            "candidate_email": getattr(resume_data, 'candidate_email', None),
                            "linkedin_url": getattr(resume_data, 'linkedin_url', None),
                            "phone": getattr(resume_data, 'phone', None),
                            "location": getattr(resume_data, 'location', None),
                        }
                    else:
                        logger.warning(f"Unknown resume data format: {type(resume_data)}")
                        failed_count += 1
                        continue
                    
                    # Check cache first
                    if candidate_service:
                        cached_data = candidate_service.get_cached_parsed_resume(
                            email=metadata.get("candidate_email"),
                            greenhouse_id=metadata.get("greenhouse_id")
                        )
                        if cached_data:
                            cache_hits += 1
                            resume = ParsedResume(
                                full_name=cached_data.get("full_name"),
                                email=cached_data.get("email"),
                                phone=cached_data.get("phone"),
                                linkedin_url=cached_data.get("linkedin_url"),
                                github_url=cached_data.get("github_url"),
                                location=cached_data.get("location"),
                                skills=cached_data.get("skills", []),
                                experience=[],
                                education=[],
                                summary=cached_data.get("summary"),
                                greenhouse_id=cached_data.get("greenhouse_id"),
                            )
                            resume.experience = cached_data.get("experience", [])
                            resume.education = cached_data.get("education", [])
                            parsed.append(resume)
                            logger.info(
                                "resume_cache_hit",
                                greenhouse_id=metadata.get("greenhouse_id"),
                                email=metadata.get("candidate_email")
                            )
                            continue
                    
                    cache_misses += 1
                    to_parse.append((idx, file_bytes, filename, metadata))
                    
                except Exception as e:
                    failed_count += 1
                    logger.warning(f"Failed to pre-process resume {idx}: {str(e)[:200]}")
            
            logger.info(
                "resume_parsing_phase1_complete",
                cache_hits=cache_hits,
                to_parse=len(to_parse),
                total_resumes=total_resumes,
                max_concurrent=MAX_CONCURRENT_PARSES
            )
            
            # Phase 2: Parse cache misses concurrently
            if to_parse:
                if analysis_id and self.event_callback:
                    self.event_callback(
                        analysis_id,
                        "resume_parsing_progress",
                        f"Parsing {len(to_parse)} resumes ({cache_hits} from cache), up to {MAX_CONCURRENT_PARSES} concurrent",
                        {"cached": cache_hits, "to_parse": len(to_parse), "total": total_resumes, "stage": "parse_resumes"}
                    )
                
                async def _parse_single(idx: int, file_bytes: bytes, filename: str, metadata: dict) -> Optional[ParsedResume]:
                    """Parse a single resume with semaphore-controlled concurrency."""
                    nonlocal completed_count, failed_count
                    
                    async with semaphore:
                        try:
                            resume = await self.resume_parser.parse_resume(
                                file_bytes=file_bytes,
                                filename=filename
                            )
                            
                            # Enrich with source metadata
                            if metadata.get("greenhouse_id"):
                                resume.greenhouse_id = metadata["greenhouse_id"]
                                logger.info(
                                    "greenhouse_id_set_on_resume",
                                    greenhouse_id=resume.greenhouse_id,
                                    candidate_email=resume.email or metadata.get("candidate_email")
                                )
                            if metadata.get("candidate_name") and not resume.full_name:
                                resume.full_name = metadata["candidate_name"]
                            if metadata.get("candidate_email") and not resume.email:
                                resume.email = metadata["candidate_email"]
                            if metadata.get("linkedin_url") and not resume.linkedin_url:
                                resume.linkedin_url = metadata["linkedin_url"]
                            if metadata.get("phone") and not resume.phone:
                                resume.phone = metadata["phone"]
                            if metadata.get("location") and not resume.location:
                                resume.location = metadata["location"]
                            
                            completed_count += 1
                            
                            if analysis_id and self.event_callback:
                                self.event_callback(
                                    analysis_id,
                                    "resume_parsed",
                                    f"Parsed {completed_count}/{len(to_parse)}: {metadata.get('candidate_name') or filename}",
                                    {"current": cache_hits + completed_count, "total": total_resumes, "filename": filename}
                                )
                            
                            return resume
                            
                        except Exception as e:
                            failed_count += 1
                            completed_count += 1
                            logger.warning(
                                "resume_parse_failed",
                                filename=filename,
                                error=str(e),
                                error_type=type(e).__name__
                            )
                            if analysis_id and self.event_callback:
                                self.event_callback(
                                    analysis_id,
                                    "resume_parse_failed",
                                    f"Failed: {metadata.get('candidate_name') or filename} - {str(e)[:100]}",
                                    {"current": cache_hits + completed_count, "total": total_resumes, "error": str(e)[:200]}
                                )
                            return None
                
                # Fire all parse tasks concurrently (semaphore limits actual concurrency)
                parse_tasks = [
                    _parse_single(idx, fb, fn, meta)
                    for idx, fb, fn, meta in to_parse
                ]
                results = await asyncio.gather(*parse_tasks)
                
                for result in results:
                    if result is not None:
                        parsed.append(result)
        
        finally:
            # Rule 16: Always close DB session in finally block
            if db is not None:
                try:
                    db.close()
                except Exception:
                    pass
        
        logger.info(
            "resume_parsing_complete",
            cache_hits=cache_hits,
            cache_misses=cache_misses,
            failed_count=failed_count,
            total_parsed=len(parsed),
            total_attempted=total_resumes
        )
        
        return parsed
    
    async def _score_candidates(
        self,
        candidates: List[ParsedResume],
        diagnostic: DiagnosticReport,
        baseline: BaselineProfile,
        source: CandidateSource
    ) -> List[CandidateScore]:
        """Stage 4/6: Score candidates."""
        scores = []
        failed_count = 0
        
        for idx, candidate in enumerate(candidates):
            try:
                # Convert ParsedResume to dict for scoring engine
                # The scoring engine expects candidate_data as a Dict[str, Any]
                candidate_data = candidate.dict() if hasattr(candidate, 'dict') else candidate.model_dump()
                
                # Generate candidate_id if not present
                candidate_id = getattr(candidate, 'candidate_id', None)
                if not candidate_id:
                    candidate_id = getattr(candidate, 'email', None) or getattr(candidate, 'candidate_name', f"candidate_{idx}")
                
                score = await asyncio.to_thread(
                    self.scoring_engine.score_candidate,
                    candidate_data=candidate_data,
                    baseline=baseline,
                    candidate_source=source,
                    candidate_id=str(candidate_id),
                    diagnostic=diagnostic
                )
                scores.append(score)
            except Exception as e:
                failed_count += 1
                candidate_name = getattr(candidate, 'candidate_name', None) or getattr(candidate, 'full_name', 'unknown')
                candidate_email = getattr(candidate, 'email', None) or 'no_email'
                logger.warning(
                    "candidate_scoring_failed",
                    candidate_name=candidate_name,
                    candidate_email=candidate_email,
                    candidate_index=idx,
                    error=str(e),
                    exc_info=True
                )
        
        if failed_count > 0:
            logger.warning(
                "scoring_completed_with_failures",
                source=source.value,
                total_candidates=len(candidates),
                scored_successfully=len(scores),
                failed_count=failed_count
            )
        
        # Sort by overall score descending
        scores.sort(key=lambda x: x.overall_score, reverse=True)
        
        return scores
    
    async def _search_market(
        self,
        diagnostic: DiagnosticReport,
        baseline: BaselineProfile,
        applicant_scores: List[CandidateScore],
        role: str
    ) -> Tuple[PDLQueryParams, List[ParsedResume]]:
        """Stage 5: Build PDL query and search market."""
        # Build query - use enhanced builder if available (has blueprint/DNA)
        if hasattr(self, 'enhanced_pdl_builder') and self.enhanced_pdl_builder:
            logger.info(
                "using_enhanced_pdl_query_builder",
                has_blueprint=self.blueprint is not None,
                has_dna=self.company_dna is not None
            )
            pdl_query = await asyncio.to_thread(
                self.enhanced_pdl_builder.build_enhanced_query,
                diagnostic=diagnostic,
                baseline=baseline,
                role=role,
                limit=self.pdl_query_limit
            )
        else:
            # Fall back to legacy builder
            pdl_query = await asyncio.to_thread(
                self.pdl_query_builder.build_initial_query,
                diagnostic=diagnostic,
                baseline=baseline,
                role=role,
                limit=self.pdl_query_limit
            )
        
        # Convert to API payload
        api_payload = self.pdl_query_builder.convert_to_pdl_api_payload(pdl_query)
        
        # Call PDL API via connector framework
        # Create a new connector configuration for this specific search query
        try:
            from src.services.ingestion.connectors.people_data_labs import PeopleDataLabsConnector
            from src.services.ingestion.connector_service import ConnectorService
            from src.models.connector import ConnectorConfiguration
            from src.models import database
            import uuid
            
            if database.SessionLocal is None:
                database.init_database()
            
            db = database.SessionLocal()
            try:
                connector_service = ConnectorService(db)
                
                # Get an existing PDL connector to copy credentials from
                # (We need API key from an existing connector)
                existing_pdl_connectors = await asyncio.to_thread(
                    connector_service.list_configurations,
                    customer_id=self.customer_id,
                    connector_type='people_data_labs',
                    is_enabled=True
                )
                
                if not existing_pdl_connectors:
                    raise ValueError("No enabled PDL connector found - need API credentials for market search")
                
                # Use credentials from first enabled connector
                api_credentials = connector_service.get_credentials(existing_pdl_connectors[0])
                
                # Create a new connector configuration for this specific query
                connector_name = f"ML Talent Market Search - {role} - {uuid.uuid4().hex[:8]}"
                # Convert PDLQueryParams to simple dict format for connector config
                # (Connector will handle conversion to Elasticsearch DSL internally)
                # Use empirically validated query format from testing
                simple_query = {}
                
                # Add job_title for specific role matching (preferred for ML engineers)
                if pdl_query.job_title:
                    simple_query["job_title"] = [pdl_query.job_title.lower()]
                
                # Add job_title_role for broad categorization (only if job_title not used)
                if pdl_query.job_title_role and not pdl_query.job_title:
                    simple_query["job_title_role"] = [r.lower() for r in pdl_query.job_title_role]
                
                # Add skills (limit to 5 max per empirical rules)
                all_skills = (pdl_query.required_skills + pdl_query.optional_skills)[:5]
                if all_skills:
                    simple_query["skills"] = [s.lower() for s in all_skills]
                
                # Add location (recommended for credit control)
                simple_query["location_country"] = ["united states"]
                
                # Note: PDL uses inferred_years_experience for experience filtering
                # but it's not a direct filter field in the search API.
                # Experience is better filtered by job_title_levels (e.g., ["senior", "manager"])
                
                new_connector = await asyncio.to_thread(
                    connector_service.create_configuration,
                    customer_id=self.customer_id,
                    connector_type='people_data_labs',
                    connector_name=connector_name,
                    description=f"Market search query for {role} talent intelligence analysis",
                    credentials=api_credentials,
                    sync_config={
                        "search_query": simple_query,
                        "max_records": self.pdl_query_limit,
                        "page_size": self.pdl_query_limit
                    },
                    tags=["ml_talent", "market_search", role.lower().replace(" ", "_")],
                    created_by_user_id=self.user_id
                )
                
                logger.info(
                    "pdl_connector_created",
                    connector_id=new_connector.connector_id,
                    connector_name=connector_name,
                    query_preview=str(simple_query)[:200]
                )
                
                # Initialize PDL connector and fetch results
                pdl_connector = PeopleDataLabsConnector(
                    credentials=api_credentials,
                    config={
                        "search_query": simple_query,
                        "max_records": self.pdl_query_limit,
                        "page_size": self.pdl_query_limit
                    },
                    customer_id=self.customer_id
                )
                
                # Search for candidates matching the profile
                logger.info("calling_pdl_api", query_version=pdl_query.version, limit=self.pdl_query_limit)
                
                # Read results from connector
                results = []
                for batch in await asyncio.to_thread(pdl_connector.read_stream, "full", {}):
                    results.extend(batch)
                    if len(results) >= self.pdl_query_limit:
                        results = results[:self.pdl_query_limit]
                        break
                
                # Log PDL API response for debugging
                logger.info(
                    "pdl_api_response",
                    result_count=len(results) if results else 0,
                    query_used=api_payload.get("query", "")[:200],  # First 200 chars of query
                    sample_result=results[0] if results and len(results) > 0 else None
                )
                
                # Convert PDL results to ParsedResume format for consistency
                market_candidates = []
                for person in results:
                    try:
                        # Extract email - handle both dict and string formats
                        email = person.get('work_email')
                        if not email and person.get('emails'):
                            emails = person.get('emails', [])
                            if emails and len(emails) > 0:
                                first_email = emails[0]
                                if isinstance(first_email, dict):
                                    email = first_email.get('address')
                                elif isinstance(first_email, str):
                                    email = first_email
                        
                        # Extract phone - handle both dict and string formats
                        phone = None
                        phone_numbers = person.get('phone_numbers', [])
                        if phone_numbers and len(phone_numbers) > 0:
                            first_phone = phone_numbers[0]
                            if isinstance(first_phone, dict):
                                phone = first_phone.get('number')
                            elif isinstance(first_phone, str):
                                phone = first_phone
                        
                        # Extract linkedin URL
                        linkedin_url = person.get('linkedin_url')
                        if linkedin_url and not linkedin_url.startswith('http'):
                            linkedin_url = f"https://{linkedin_url}"
                        
                        # Convert PDL person to ParsedResume format
                        # Build experience list from PDL data
                        experience_list = []
                        for job in person.get('experience', [])[:5]:  # Limit to recent 5 jobs
                            company_data = job.get('company', {})
                            title_data = job.get('title', {})
                            experience_list.append(ParsedExperience(
                                company=company_data.get('name') if isinstance(company_data, dict) else company_data,
                                title=title_data.get('name') if isinstance(title_data, dict) else title_data,
                                start_date=job.get('start_date'),
                                end_date=job.get('end_date'),
                                description=None,
                                is_current=job.get('is_primary', False)
                            ))
                        
                        # Build education list from PDL data
                        education_list = []
                        for school in person.get('education', []):
                            school_data = school.get('school', {})
                            education_list.append(ParsedEducation(
                                institution=school_data.get('name') if isinstance(school_data, dict) else school_data,
                                degree=school.get('degrees', [None])[0] if school.get('degrees') else None,
                                field_of_study=school.get('majors', [None])[0] if school.get('majors') else None,
                                start_date=school.get('start_date'),
                                end_date=school.get('end_date')
                            ))
                        
                        parsed = ParsedResume(
                            full_name=person.get('full_name', 'Unknown'),
                            email=email,
                            phone=phone,
                            linkedin_url=linkedin_url,
                            current_title=person.get('job_title'),
                            current_company=person.get('job_company_name'),
                            skills=person.get('skills', []) if isinstance(person.get('skills'), list) else [],
                            experience=experience_list,
                            education=education_list,
                            certifications=[],  # PDL doesn't provide this directly
                            location=person.get('location_name'),
                            parse_confidence=0.95,  # High confidence for PDL data
                            quality_flags=[]  # No quality issues for PDL data
                        )
                        
                        # Store PDL ID in a way we can use later for tracking
                        parsed._pdl_id = f"pdl_{person.get('id', person.get('pdl_id', 'unknown'))}"
                        market_candidates.append(parsed)
                    except Exception as parse_error:
                        logger.warning(
                            "pdl_result_parse_failed",
                            error=str(parse_error),
                            person_id=person.get('id', 'unknown')
                        )
                
                logger.info(
                    "pdl_market_search_complete",
                    query_version=pdl_query.version,
                    candidates_found=len(market_candidates)
                )
                
            finally:
                db.close()
                
        except Exception as e:
            error_str = str(e)
            
            # Check for PDL quota exceeded error
            from src.services.ingestion.connectors.people_data_labs import PDLQuotaExceededError, PDLAuthenticationError
            
            if isinstance(e, PDLQuotaExceededError):
                logger.warning(
                    "pdl_quota_exceeded",
                    error=error_str,
                    query_version=pdl_query.version
                )
                # Emit user-friendly event
                if self.event_callback:
                    self.event_callback(
                        self._current_analysis_id if hasattr(self, '_current_analysis_id') else "unknown",
                        "market_search_quota_exceeded",
                        "Market candidate search skipped: PDL API credits exhausted. "
                        "Please contact your administrator to add more credits. "
                        "Analysis will continue with uploaded/ATS candidates only.",
                        {"error_type": "quota_exceeded", "recoverable": True}
                    )
            elif isinstance(e, PDLAuthenticationError):
                logger.error(
                    "pdl_authentication_failed",
                    error=error_str,
                    query_version=pdl_query.version
                )
                if self.event_callback:
                    self.event_callback(
                        self._current_analysis_id if hasattr(self, '_current_analysis_id') else "unknown",
                        "market_search_auth_failed",
                        "Market candidate search skipped: PDL API authentication failed. "
                        "Please contact your administrator to update API credentials. "
                        "Analysis will continue with uploaded/ATS candidates only.",
                        {"error_type": "auth_failed", "recoverable": True}
                    )
            elif "402" in error_str or "payment_required" in error_str.lower() or "quota" in error_str.lower():
                # Catch any other quota-related errors by string matching
                logger.warning(
                    "pdl_quota_exceeded_generic",
                    error=error_str,
                    query_version=pdl_query.version
                )
                if self.event_callback:
                    self.event_callback(
                        self._current_analysis_id if hasattr(self, '_current_analysis_id') else "unknown",
                        "market_search_quota_exceeded",
                        "Market candidate search skipped: PDL API credits exhausted. "
                        "Analysis will continue with uploaded/ATS candidates only.",
                        {"error_type": "quota_exceeded", "recoverable": True}
                    )
            else:
                logger.error(
                    "pdl_market_search_failed",
                    error=error_str,
                    query_version=pdl_query.version,
                    exc_info=True
                )
                if self.event_callback:
                    self.event_callback(
                        self._current_analysis_id if hasattr(self, '_current_analysis_id') else "unknown",
                        "market_search_failed",
                        f"Market candidate search failed: {error_str[:100]}. "
                        "Analysis will continue with uploaded/ATS candidates only.",
                        {"error_type": "unknown", "recoverable": True}
                    )
            
            # Return empty list on error, don't fail entire analysis
            market_candidates = []
        
        return pdl_query, market_candidates
    
    async def _run_synthesis(
        self,
        diagnostic: DiagnosticReport,
        applicant_scores: List[CandidateScore],
        market_scores: List[CandidateScore],
        top_overall_count: int = 3
    ) -> SynthesisReport:
        """Stage 7: Run synthesis agent."""
        synthesis_agent = SynthesisAgentService(
            customer_id=self.customer_id,
            user_id=self.user_id,
            llm_provider="openai",
            llm_model="gpt-4o-mini"  # Changed from gpt-4o due to quota limits
        )
        
        synthesis_input = SynthesisInput(
            diagnostic_report=diagnostic,
            applicant_scores=applicant_scores,
            market_scores=market_scores,
            top_overall_count=top_overall_count
        )
        
        return await asyncio.to_thread(
            synthesis_agent.synthesize,
            synthesis_input
        )
