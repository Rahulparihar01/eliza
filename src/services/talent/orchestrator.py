"""
Talent Intelligence Flow - Main Orchestration

This is the primary flow that orchestrates the entire Talent Intelligence pipeline:
1. Parse job description + ideal candidate description
2. Build baseline profile from Neo4j (current employees in target role)
3. Run diagnostic agent to prioritize attributes
4. Parse applicant resumes (50 max)
5. Build PDL query and search market (50 results)
6. Score all candidates (applicants + market)
7. Run synthesis agent to produce final report
8. Store results with provenance

Role-agnostic: supports any role type, driven by the job description and user configuration.
"""

